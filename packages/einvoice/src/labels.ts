export type LabelKey = keyof (typeof LABELS)['de'];

export function label(lang: Lang, key: LabelKey, vars: Record<string, string> = {}): string {
  return LABELS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '');
}

