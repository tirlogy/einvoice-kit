/** Title for a UNTDID 1001 type code. */
export function documentTitle(typeCode: string, lang: Lang, cancellation = false): string {
  if (cancellation) return label(lang, 'cancellation');
  const map: Record<string, LabelKey> = {
    '380': 'invoice',
    '381': 'creditNote',
    '386': 'prepayment',
    '326': 'partial',
    '875': 'partial',
    '877': 'finalInvoice',
    '384': 'corrected',
    '389': 'selfBilled',
  };
  return label(lang, map[typeCode] ?? 'invoice');
}
